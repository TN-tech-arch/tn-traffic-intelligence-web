import { chromium } from 'playwright'

const b = await chromium.launch({ headless: true })
const p = await b.newPage({ viewport: { width: 1500, height: 1100 } })
await p.goto('http://127.0.0.1:8077/exploration', { waitUntil: 'networkidle' })
await p.waitForTimeout(5000)
p.on('request', (r) => {
  if (r.url().includes('/api/analysis/temporal')) console.log('REQ temporal', r.postData()?.match(/"acf_max_lag":\d+/)?.[0])
})
p.on('response', (r) => {
  if (r.url().includes('/api/analysis/temporal')) console.log('RES temporal', r.status())
})
const card = p.locator('.ant-card', { hasText: 'ACF 与趋势' }).first()
const sw = card.locator('.ant-switch').first()
console.log('initial checked:', await sw.getAttribute('aria-checked'))
await sw.click()
await p.waitForTimeout(3000)
console.log('after 1st click:', await sw.getAttribute('aria-checked'), 'input exists:', await p.locator('[data-field="m1.acf_max_lag"] input').count())
const input = p.locator('[data-field="m1.acf_max_lag"] input').first()
await input.click({ clickCount: 3 })
await input.fill('200')
await p.keyboard.press('Tab')
await p.waitForTimeout(4000)
console.log('after manual 200:', (await card.innerText()).match(/实际生效：.*/)?.[0])
await input.click({ clickCount: 3 })
await input.fill('5000')
await p.keyboard.press('Tab')
await p.waitForTimeout(3000)
console.log('after 5000, errors:', await p.locator('[data-field="m1.acf_max_lag"] .tn-error-text').count())
await sw.click()
await p.waitForTimeout(6000)
console.log('after 2nd click:', await sw.getAttribute('aria-checked'), 'input exists:', await p.locator('[data-field="m1.acf_max_lag"] input').count())
console.log('auto line:', (await card.innerText()).match(/实际生效 Max Lag：.*/)?.[0])
const insight = await p.locator('.tn-insight-card', { hasText: 'ACF & Trend Insights' }).first().innerText()
console.log('periodicity line:', insight.split('\n').find((l) => l.includes('周期性'))?.slice(0, 300))
await b.close()
