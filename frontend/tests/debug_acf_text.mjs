import { chromium } from 'playwright'

const b = await chromium.launch({ headless: true })
const p = await b.newPage({ viewport: { width: 1500, height: 1000 } })
await p.goto('http://127.0.0.1:8077/exploration', { waitUntil: 'networkidle' })
await p.waitForTimeout(5000)
const end = p.locator('[data-field="m1.time_end"] input').first()
await end.click()
await end.fill('2013-11-15 23:50')
await p.keyboard.press('Enter')
await p.waitForTimeout(5000)
const start = p.locator('[data-field="m1.time_start"] input').first()
await start.click()
await start.fill('2013-11-02 00:00')
await p.keyboard.press('Enter')
await p.waitForTimeout(6000)
const card = p.locator('.tn-insight-card', { hasText: 'ACF & Trend Insights' }).first()
console.log(await card.innerText())
await b.close()
