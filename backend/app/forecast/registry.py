def public_registry() -> list[dict[str, Any]]:
    """Registry payload for GET /api/models/registry (foundation options injected)."""
    from app.forecast.foundation import chronos_status, timesfm_status

    dynamic = {"timesfm": timesfm_status(), "chronos": chronos_status()}
    registry = []
    for model in MODELS:
        entry = {
            "key": model["key"],
            "index": model["index"],
            "label": model["label"],
            "category": model["category"],
            "category_label": model["category_label"],
            "category_label_zh": model["category_label_zh"],
            "usage_zh": model["usage_zh"],
            "default_mode": model["default_mode"],
            "supported_modes": model["supported_modes"],
            "capabilities": dict(model["capabilities"]),
            "params": [dict(p) for p in model["params"]],
        }
        status = dynamic.get(model["key"])
        if status:
            entry["foundation_status"] = status
            entry["capabilities"].update(
                {
                    "supports_finetune": status.get("supports_finetune", False),
                    "max_context": status.get("max_context"),
                    "installed": status.get("installed"),
                    "device_available": status.get("device_available"),
                }
            )
            checkpoint_param = next(p for p in entry["params"] if p["key"] == "checkpoint_id")
            checkpoint_param["enum"] = [c["id"] for c in status["checkpoints"]]
            checkpoint_param["enum_labels"] = [
                f"{c['id']} ({c['license']})" + ("" if c["available"] else " — 未下载")
                for c in status["checkpoints"]
            ]
            checkpoint_param["enum_meta"] = status["checkpoints"]
            if status["checkpoints"]:
                checkpoint_param["default"] = status["default_checkpoint"]
        registry.append(entry)
    return registry
